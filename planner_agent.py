# Keys the plan JSON must contain, and the only actions allowed in the system.
REQUIRED_KEYS = {"strategy", "decisions", "stop_point"}
VALID_ACTIONS = {"FORWARD", "LEFT", "RIGHT", "STOP"}
MAX_ATTEMPTS = 3

SYSTEM_PROMPT = """You are a navigation planner (the "Planner Agent") for a mobile robot navigation system.

ROLE:
You receive the validated requirements produced by the Analyst Agent and turn them into a concrete navigation plan.

TASK:
Read the requirements JSON provided by the user and return ONE JSON object that describes the navigation plan.

The JSON object must contain EXACTLY these three keys and no others:
- "strategy": (string) a short description of the navigation strategy. It must say that the robot prefers moving toward its goal whenever this can be done safely, and that it never moves into a blocked direction.
- "decisions": (array of strings) the list of decisions the robot can take during navigation. It must contain exactly these four values and no others, in any order: "FORWARD", "LEFT", "RIGHT", "STOP".
- "stop_point": (string) the condition under which the robot must stop, i.e. when no safe direction is available.

RULES AND CONSTRAINTS:
1. The only allowed actions in the whole system are FORWARD, LEFT, RIGHT, STOP. Never introduce any other action.
2. The robot should prefer moving toward its goal whenever this can be done safely.
3. The robot must never move into a blocked direction.
4. If no safe direction is available, the robot must stop.
5. Output valid JSON only. Do not output markdown, code fences, comments or any explanatory text.
"""


## Function to validate the plan generated by the Planner Agent
## It should first check that the parameter it receives is of the correct type. 
# Then, it should validate all the keys and values contained in the above Python data structure of the input parameter.
def validate_plan(data):
    if not isinstance(data, dict):
        raise ValueError(
            "Plan must be a JSON object (dict), got %s."
            % type(data).__name__
        )

    keys = set(data.keys())
    missing = REQUIRED_KEYS - keys
    extra = keys - REQUIRED_KEYS
    if missing:
        raise ValueError("Missing required key(s): %s" % sorted(missing))
    if extra:
        raise ValueError("Unexpected key(s) introduced by the model: %s" % sorted(extra))

    strategy = data["strategy"]
    if not isinstance(strategy, str) or not strategy.strip():
        raise ValueError('"strategy" must be a non-empty string.')

    decisions = data["decisions"]
    if not isinstance(decisions, list) or not decisions:
        raise ValueError('"decisions" must be a non-empty list.')
    if not all(isinstance(decision, str) for decision in decisions):
        raise ValueError('"decisions" must contain only strings.')
    invalid = set(decisions) - VALID_ACTIONS
    if invalid:
        raise ValueError(
            '"decisions" contains invalid action(s): %s. '
            "Only FORWARD, LEFT, RIGHT, STOP are allowed." % sorted(invalid)
        )
    if set(decisions) != VALID_ACTIONS:
        raise ValueError(
            '"decisions" must contain exactly %s, got %s.'
            % (sorted(VALID_ACTIONS), sorted(set(decisions)))
        )

    stop_point = data["stop_point"]
    if not isinstance(stop_point, str) or not stop_point.strip():
        raise ValueError('"stop_point" must be a non-empty string.')

    return data


## Function to run the Planner Agent
## It takes the requirements generated by the Analyst Agent as input, sends them to the Planner Agent. Just like you did with the Analyst Agent.
## Take the response from the Planner Agent (Qwen), parse it and validate it using the validate_plan function, and return the validated plan.
def run_planner(requirement):
    client = get_client()
    last_error = None
    for attempt in range(1, MAX_ATTEMPTS + 1):
        response = client.chat.completions.create(
            model=MODEL,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": json.dumps(requirement, ensure_ascii=False)},
            ],
            temperature=0.0,
        )
        raw_text = response.choices[0].message.content
        try:
            data = _parse_json(raw_text)
            return validate_plan(data)
        except (json.JSONDecodeError, ValueError) as error:
            last_error = error
            print("[planner_agent] attempt %d failed: %s" % (attempt, error))
    raise RuntimeError(
        "Planner Agent failed to produce a valid plan after %d "
        "attempts. Last error: %s" % (MAX_ATTEMPTS, last_error)
    )


